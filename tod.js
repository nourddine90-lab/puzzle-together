// Ids come from the text itself (not list position), so items can be added, reordered or moved to
// the weekly extras file without ever being mistaken for one already played.
export function todId(kind, t) {
  let h = 0x811c9dc5;
  for (const ch of kind + '|' + t.trim()) { h ^= ch.codePointAt(0); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(36);
}
const flat = (kind, groups) => Object.entries(groups).flatMap(([c, list]) => list.map((t) => ({ kind, c, t, id: todId(kind, t) })));
